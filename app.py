def question(n):

    if "name" not in session:
        return redirect(
            url_for("home")
        )

    con = db()

    questions = con.execute(
        "SELECT * FROM questions ORDER BY id"
    ).fetchall()

    con.close()

    total = len(questions)

    if total == 0:
        return redirect(
            url_for("home")
        )

    if n >= total:
        return redirect(
            url_for("finish")
        )

    if request.method == "POST":

        selected = request.form.get(
            "answer"
        )

        answers = session.get(
            "answers",
            {}
        )

        # Cavab verilibsə yadda saxla
        if selected in ["A", "B", "C", "D"]:

            answers[str(n)] = selected

            session["answers"] = answers

        # TESTİ BİTİR düyməsi
        action = request.form.get(
            "action"
        )

        if action == "finish":

            return redirect(
                url_for("finish")
            )

        # NÖVBƏTİ
        return redirect(
            url_for(
                "question",
                n=n + 1
            )
        )

    return render_template(
        "question.html",
        q=questions[n],
        n=n,
        total=total,
        name=session["name"]
    )


